      <h2>제1조(개인정보의 처리목적)</h2>
      <p>
        ① 회사는 다음의 목적을 위하여 개인정보를 처리합니다. 처리 중인
        개인정보는 명시된 목적 외의 용도로 이용되지 않으며, 목적이 변경되는 경우
        개인정보 보호법 제18조에 따라 별도 동의를 받는 등 필요한 조치를
        이행합니다.
      </p>
      <ol>
        <li>
          <strong>회원 가입 및 관리</strong>: 가입 의사 확인, 본인 식별·인증,
          SNS 계정 연동, 부정 이용 방지, 이용대금 청구 등
        </li>
        <li>
          <strong>민원사무 처리</strong>: 민원인의 신원 확인, 민원사항 확인,
          사실조사를 위한 연락·통지, 처리결과 통보 등
        </li>
      </ol>
      <p>
        ② 회사가 개인정보 보호법 제32조에 따라 등록·공개하는 개인정보파일의
        처리목적은 관련 포털(privacy.go.kr)을 통해 확인하실 수 있습니다.
      </p>
    </section>

    <section>
      <h2>제2조(개인정보의 처리 및 보유기간)</h2>
      <p>
        ① 회사는 법령에 따른 보유·이용 기간 또는 정보주체로부터 동의받은 기간
        내에서 개인정보를 처리·보유합니다.
      </p>
      <p>② 각각의 처리 및 보유기간은 다음과 같습니다.</p>
      <ol>
        <li>회원 가입 및 관리: 탈퇴 시까지</li>
        <li>민원사무 처리: 민원처리 종료 후 3년</li>
      </ol>
    </section>

    <section>
      <h2>제3조(개인정보의 제3자 제공)</h2>
      <p>
        ① 회사는 정보주체의 사전 동의 없이 개인정보를 무단 제공하지 않습니다.
      </p>
      <p>
        ② 서비스 특성상 이용자 정보가 의료기관에 제공될 수 있으나, 이는 이용자가
        처리·전달을 요청한 경우에 한정됩니다. 별도 공개되지 않은 정보를
        제3자에게 제공하지 않습니다.
      </p>
    </section>

